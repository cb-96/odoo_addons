import { readFile } from 'node:fs/promises';
import assert from 'node:assert/strict';
const source = await readFile(new URL('../sports_federation_live_workspace/static/src/visual_helpers.js', import.meta.url), 'utf8');
const { destinationLabel, canApply, comparable, navigationTarget } = await import('data:text/javascript;base64,' + Buffer.from(source).toString('base64'));
assert.equal(destinationLabel(null), 'Not assessed');
assert.equal(destinationLabel({valid: false, warnings: []}), 'Blocked: mandatory rule');
assert.equal(destinationLabel({valid: true, unchanged: true, warnings: []}), 'Current slot');
assert.equal(destinationLabel({valid: true, warnings: [{}]}), 'Allowed: preference warning');
assert.equal(destinationLabel({valid: true, warnings: []}), 'Allowed destination');
assert.equal(canApply(null, 'reason'), false);
assert.equal(canApply({after: {validation: {errors: []}}}, ''), false);
assert.equal(canApply({after: {validation: {errors: [{}]}}}, 'reason'), false);
assert.equal(canApply({after: {validation: {errors: []}}}, 'reason'), true);
assert.equal(comparable({id: 1, signature: 'a', revision: 1}, {id: 2, signature: 'a', revision: 1}), true);
assert.equal(comparable({id: 1, signature: 'a', revision: 1}, {id: 1, signature: 'a', revision: 1}), false);
assert.equal(comparable({id: 1, signature: 'a', revision: 1}, {id: 2, signature: 'b', revision: 1}), false);
assert.equal(comparable({id: 1, signature: 'a', revision: 1}, {id: 2, signature: 'a', revision: 2}), false);
const cells = [{row:1,column:1},{row:1,column:2},{row:2,column:2},{row:3,column:1}];
assert.equal(navigationTarget(cells,0,'ArrowDown'),3);
assert.equal(navigationTarget(cells,2,'ArrowUp'),1);
assert.equal(navigationTarget(cells,0,'ArrowRight'),1);
assert.equal(navigationTarget(cells,2,'ArrowLeft'),2);
assert.equal(navigationTarget(cells,1,'End'),3);
console.log('18 visual helper assertions passed');
