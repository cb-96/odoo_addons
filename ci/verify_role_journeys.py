#!/usr/bin/env python3
"""Validate role-journey evidence; missing evidence blocks, never implies completion.

This validates evidence integrity and coverage, not the quality of assertions or
independent authenticity of participant observations. Human review is mandatory.
"""
import argparse
import hashlib
import json
import math
from pathlib import Path
import subprocess
import sys

ROOT = Path(__file__).resolve().parents[1]
SPEC = ROOT / 'ci/role_journeys/acceptance.json'

def digest(path):
    h = hashlib.sha256()
    with Path(path).open('rb') as stream:
        for chunk in iter(lambda: stream.read(1024 * 1024), b''): h.update(chunk)
    return h.hexdigest()

def load(path): return json.loads(Path(path).read_text())

def requirements(spec):
    return [role + '.' + check for role, checks in spec['journeys'].items() for check in checks] + ['shared.' + check for check in spec['shared_checks']]

def validate(spec, report, root, commit):
    errors = []
    root = Path(root).resolve()
    if report.get('commit') != commit: errors.append('Evidence does not match the final candidate commit.')
    if report.get('status') != 'passed': errors.append('Journey execution report is not passing.')
    if report.get('spec_sha256') != digest(SPEC): errors.append('Acceptance specification checksum mismatch.')
    checks = report.get('checks', {})
    if not isinstance(checks, dict): return errors + ['checks must be an object.']
    for key in requirements(spec):
        item = checks.get(key, {})
        if not isinstance(item, dict) or item.get('status') != 'passed':
            errors.append('Missing passing check: ' + key); continue
        if not item.get('test_id') or type(item.get('tests_executed')) is not int or item['tests_executed'] < 1 or item.get('exit_code') != 0:
            errors.append('No successful executed test for: ' + key)
        evidence = item.get('evidence', [])
        if not isinstance(evidence, list) or not evidence:
            errors.append('No evidence artifacts for: ' + key); continue
        for entry in evidence:
            if not isinstance(entry, dict) or not isinstance(entry.get('path'), str):
                errors.append('Invalid artifact entry: ' + key); continue
            path = (root / entry['path']).resolve()
            if root not in path.parents or not path.is_file() or path.stat().st_size == 0:
                errors.append('Missing or unsafe artifact: ' + entry['path']); continue
            if digest(path) != entry.get('sha256'): errors.append('Artifact checksum mismatch: ' + entry['path'])
    # Observations are recorded by the facilitator after real sessions, never generated by a model.
    observations = report.get('novice_observations', [])
    if not isinstance(observations, list): observations = []; errors.append('Invalid novice observations.')
    gate = spec['novice_gate']
    seen = set()
    for row in observations:
        if not isinstance(row, dict): errors.append('Invalid novice observation.'); continue
        if not isinstance(row.get('participant_code'), str) or not isinstance(row.get('task'), str):
            errors.append('Participant code and task must be strings.'); continue
        pair = (row.get('participant_code'), row.get('task'))
        if pair in seen: errors.append('Duplicate participant/task observation.'); continue
        seen.add(pair)
        if not pair[0] or pair[1] not in spec['novice_tasks']: errors.append('Unknown task or missing participant code.')
        if type(row.get('completed')) is not bool or type(row.get('facilitator_interventions')) is not int or row.get('facilitator_interventions', -1) < 0:
            errors.append('Invalid completion/intervention observation.')
        if type(row.get('elapsed_seconds')) not in (int, float) or not math.isfinite(row.get('elapsed_seconds', -1)) or row.get('elapsed_seconds', -1) < 0:
            errors.append('Missing valid elapsed time.')
        if type(row.get('critical_incidents')) is not int or row.get('critical_incidents', -1) < 0:
            errors.append('Missing incident count.')
        elif row['critical_incidents'] > gate['critical_incidents_allowed']:
            errors.append('Critical novice incident: ' + str(pair))
    for task in spec['novice_tasks']:
        rows = [r for r in observations if isinstance(r, dict) and r.get('task') == task]
        participants = {r.get('participant_code') for r in rows if isinstance(r.get('participant_code'), str) and r.get('participant_code')}
        if len(participants) < gate['minimum_participants']:
            errors.append('Insufficient real novice observations: ' + task)
        if rows:
            success = sum(r.get('completed') is True and r.get('facilitator_interventions') == 0 for r in rows)
            if success / len(rows) < gate['minimum_unassisted_completion_rate_per_task']:
                errors.append('Unassisted completion gate failed: ' + task)
    return errors

def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('--evidence-dir', type=Path, required=True)
    p.add_argument('--release-confidence', type=Path, required=True)
    a = p.parse_args()
    try:
        commit = subprocess.run(['git', 'rev-parse', 'HEAD'], cwd=ROOT, check=True, capture_output=True, text=True).stdout.strip()
        dirty = subprocess.run(['git', 'status', '--porcelain', '--untracked-files=all'], cwd=ROOT, check=True, capture_output=True, text=True).stdout.strip()
        report = load(a.evidence_dir / 'journey-execution.json')
        errors = validate(load(SPEC), report, a.evidence_dir, commit)
        if dirty: errors.append('Candidate worktree is dirty.')
        release = load(a.release_confidence)
        if release.get('commit') != commit or release.get('status') != 'passed' or release.get('blockers'):
            errors.append('Fresh release confidence for the final candidate is missing or blocked.')
        output = {'commit': commit, 'status': 'blocked' if errors else 'passed', 'blockers': errors,
                  'scope': 'Evidence gate only. Human assertion review and release authorisation remain required.'}
        (a.evidence_dir / 'role-journey-gate.json').write_text(json.dumps(output, indent=2) + '\n')
        print(json.dumps(output, indent=2))
        return 1 if errors else 0
    except (OSError, ValueError, TypeError, KeyError, subprocess.CalledProcessError) as exc:
        print('BLOCKED: ' + str(exc), file=sys.stderr); return 2

if __name__ == '__main__': raise SystemExit(main())
